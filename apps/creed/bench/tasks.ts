export function selectBenchTasks(ids: string[]) {
  if (ids.length === 0) return BENCH_TASKS;
  const selected = BENCH_TASKS.filter((item) => ids.includes(item.id));
  const missing = ids.filter((id) => !selected.some((item) => item.id === id));
  if (missing.length) throw new Error(`Unknown task IDs: ${missing.join(", ")}`);
  return selected;
}
