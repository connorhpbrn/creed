function proposalWorld() {
  const value = world("proposals_only");
  value.sections = value.sections.map((section) =>
    section.permission === "hidden" ? section : { ...section, permission: "propose" },
  );
  return value;
}

function task(
  value: Omit<BenchTask, "difficulty" | "forbiddenTools" | "answerTermGroups" | "maxTurns"> &
    Partial<Pick<BenchTask, "difficulty" | "forbiddenTools" | "answerTermGroups" | "maxTurns">>,
): BenchTask {
  return {
    difficulty: 1,
    forbiddenTools: [],
    answerTermGroups: [],
    maxTurns: 10,
    ...value,
  };
}

